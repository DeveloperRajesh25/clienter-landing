import type { MetadataRoute } from 'next'
import { SITE_URL } from '@/lib/site'

/**
 * Robots policy. Marketing pages are crawlable; private app surfaces, auth
 * pages, the admin panel, and API routes are kept out of the index.
 */
export default function robots(): MetadataRoute.Robots {
  // Private app surfaces that no crawler (search or AI) should index.
  const PRIVATE = [
    '/api/',
    '/admin',
    '/admin/',
    '/dashboard',
    '/portal',
    '/clients',
    '/projects',
    '/meetings',
    '/tasks',
    '/payments',
    '/billing',
    '/settings',
    '/team',
    '/teammate',
    '/onboarding',
    '/login',
    '/signup',
    '/team-login',
    '/auth',
    '/diagnostics',
  ]

  // AI answer-engine crawlers we explicitly welcome. Grouped by purpose so the
  // intent is unambiguous and survives any future tightening of the '*' rule:
  //  - search discovery (feeds the answer product's index)
  //  - user-triggered retrieval (a person asked the assistant to fetch a page)
  //  - model training / grounding
  // All are allowed the public marketing site and kept out of private surfaces,
  // exactly like a search engine. The machine-readable briefs for them live at
  // /llms.txt, /llms-full.txt and /pricing.md.
  const AI_BOTS = [
    'OAI-SearchBot', // ChatGPT search discovery
    'ChatGPT-User', // ChatGPT user-triggered fetch
    'GPTBot', // OpenAI training/grounding
    'Claude-SearchBot', // Claude search discovery
    'Claude-User', // Claude user-triggered fetch
    'ClaudeBot', // Anthropic training/grounding
    'PerplexityBot', // Perplexity search discovery
    'Perplexity-User', // Perplexity user-triggered fetch
    'Google-Extended', // Gemini grounding/training (does not affect Search)
    'Applebot-Extended',
    'cohere-ai',
    'Bytespider',
    'Amazonbot',
    'Meta-ExternalAgent',
  ]

  return {
    rules: [
      {
        userAgent: '*',
        allow: '/',
        disallow: PRIVATE,
      },
      {
        userAgent: AI_BOTS,
        allow: '/',
        disallow: PRIVATE,
      },
    ],
    // profiles-sitemap.xml is generated by the app (business pages + marketplace)
    // and proxied here — see the rewrites in next.config.js.
    sitemap: [`${SITE_URL}/sitemap.xml`, `${SITE_URL}/profiles-sitemap.xml`],
    host: SITE_URL,
  }
}
